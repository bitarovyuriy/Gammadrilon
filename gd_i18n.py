def current() -> str:
    return _current

def available() -> tuple[str, ...]:
    return LANGS


def detect() -> str:
    """Язык по системной локали: русская — ru, иначе en."""
    try:
        from PyQt5.QtCore import QLocale

        name = QLocale.system().name()
        return "ru" if name.startswith("ru") else "en"
    except Exception:  # noqa: BLE001
        return "ru"


def set_language(name: str, config: dict | None = None, save_fn=None) -> str:
    global _current
    _current = name if name in LANGS else "ru"
    if config is not None:
        try:
            config.setdefault("settings", {})["language"] = _current
            if save_fn is not None:
                save_fn(config)
        except Exception:  # noqa: BLE001
            pass
    return _current


def t(key: str, **fmt) -> str:
    """Перевод: сначала ключи вида "tab.cpu", затем прямые русские строки (DIRECT)."""
    if _current == "en":
        text = (STRINGS["en"].get(key) or DIRECT.get(key)
                or STRINGS["ru"].get(key) or key)
    else:
        text = STRINGS["ru"].get(key) or key
    if fmt:
        try:
            return text.format(**fmt)
        except Exception:  # noqa: BLE001
            return text
    return text


